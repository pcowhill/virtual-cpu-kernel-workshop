/**
 * Vite plugin: emits sw.js, a service worker that precaches every file of the
 * production build (the app, the machine worker, bundled sources, lessons and
 * documentation) under a cache named after a hash of those files' contents.
 * A new build therefore gets a new cache; the old one is deleted when the new
 * worker activates.
 */
import { createHash } from 'node:crypto';
import { readdirSync, readFileSync, statSync } from 'node:fs';
import { join, relative } from 'node:path';
import type { Plugin } from 'vite';

function publicFiles(dir: string): string[] {
  const out: string[] = [];
  const walk = (d: string) => {
    for (const name of readdirSync(d)) {
      const p = join(d, name);
      if (statSync(p).isDirectory()) walk(p);
      else out.push(relative(dir, p).split('\\').join('/'));
    }
  };
  walk(dir);
  return out;
}

export function serviceWorker(publicDir = 'public'): Plugin {
  return {
    name: 'vck-service-worker',
    apply: 'build',
    generateBundle(_options, bundle) {
      const hash = createHash('sha256');
      const files: string[] = [];
      for (const [name, item] of Object.entries(bundle).sort(([a], [b]) => a.localeCompare(b))) {
        if (name.endsWith('.map')) continue;
        files.push(name);
        hash.update(name);
        hash.update(item.type === 'chunk' ? item.code : item.source);
      }
      for (const name of publicFiles(publicDir).sort()) {
        files.push(name);
        hash.update(name);
        hash.update(readFileSync(join(publicDir, name)));
      }
      const version = hash.digest('hex').slice(0, 16);
      this.emitFile({ type: 'asset', fileName: 'sw.js', source: swSource(version, files) });
    },
  };
}

function swSource(version: string, files: string[]): string {
  return `// Generated by scripts/service-worker.ts. Cache version ${version}.
const CACHE = 'vck-${version}';
const PRECACHE = ${JSON.stringify(['./', ...files.filter((f) => f !== 'index.html')], null, 0)};

self.addEventListener('install', (event) => {
  // cache: 'reload' bypasses the HTTP cache, so a new worker never stores a stale
  // index.html (GitHub Pages serves it with max-age) next to the new assets.
  event.waitUntil(caches.open(CACHE).then((c) => c.addAll(PRECACHE.map((u) => new Request(u, { cache: 'reload' })))));
});

self.addEventListener('activate', (event) => {
  event.waitUntil(
    caches
      .keys()
      .then((keys) => Promise.all(keys.filter((k) => k.startsWith('vck-') && k !== CACHE).map((k) => caches.delete(k))))
      .then(() => self.clients.claim()),
  );
});

self.addEventListener('message', (event) => {
  if (event.data === 'SKIP_WAITING') self.skipWaiting();
});

/** Look up a request in this version's cache only. */
function fromCache(req) {
  return caches.open(CACHE).then((c) => c.match(req, { ignoreSearch: true, ignoreVary: true }));
}

self.addEventListener('fetch', (event) => {
  const req = event.request;
  if (req.method !== 'GET') return;
  const url = new URL(req.url);
  const scope = new URL(self.registration.scope);
  if (url.origin !== scope.origin || !url.pathname.startsWith(scope.pathname)) return;
  if (req.mode === 'navigate') {
    // The app is a single page: every navigation inside the scope is the app shell.
    event.respondWith(fromCache('./').then((r) => r || fetch(req)));
    return;
  }
  event.respondWith(fromCache(req).then((r) => r || fetch(req)));
});
`;
}
